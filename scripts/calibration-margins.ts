/** A growth machine must keep at least this share of every band edge. */
export const MIN_GROWTH_MARGIN = 0.015;
/** A metric closer than this share of its band edge is listed as near an edge. */
export const NEAR_EDGE = 0.03;
export const NEAR_EDGE_BEGIN = '<!-- near-edge:begin (generated by npm run test:vehicles) -->';
export const NEAR_EDGE_END = '<!-- near-edge:end -->';

export interface CalibrationComparison {
  metric: string;
  measured: number | null;
  coarseDt: number | null;
  band: readonly [number, number];
}
export interface CalibrationReport {
  vehicles: Record<string, { name: string; comparison: CalibrationComparison[] }>;
}
export interface BandMargin {
  id: string;
  name: string;
  metric: string;
  edge: 'floor' | 'ceiling';
  /** The measurement nearer the edge of the two timesteps. */
  value: number;
  bound: number;
  /** Distance to that edge as a share of the edge value (negative: outside). */
  margin: number;
}
/** Nearest band edge of one metric, over both timesteps. */
export function bandMargin(id: string, name: string, c: CalibrationComparison): BandMargin | null {
  if (c.measured === null || c.coarseDt === null) return null;
  const [lo, hi] = c.band,
    low = Math.min(c.measured, c.coarseDt),
    high = Math.max(c.measured, c.coarseDt),
    floor = (low - lo) / Math.abs(lo),
    ceiling = (hi - high) / Math.abs(hi);
  return floor <= ceiling
    ? { id, name, metric: c.metric, edge: 'floor', value: low, bound: lo, margin: floor }
    : { id, name, metric: c.metric, edge: 'ceiling', value: high, bound: hi, margin: ceiling };
}
/** Every metric of every machine, nearest edge first. */
export function bandMargins(report: CalibrationReport): BandMargin[] {
  const rows: BandMargin[] = [];
  for (const [id, entry] of Object.entries(report.vehicles))
    for (const c of entry.comparison) {
      const m = bandMargin(id, entry.name, c);
      if (m) rows.push(m);
    }
  return rows.sort((a, b) => a.margin - b.margin || a.id.localeCompare(b.id));
}
const METRIC: Record<string, [label: string, digits: number, unit: string]> = {
  accel0to100: ['0–100', 2, ' s'],
  topSpeed: ['top speed', 1, ' km/h'],
  braking100Distance: ['100–0', 2, ' m'],
  lateral80G: ['g at 80 km/h', 3, ' g'],
};
/** Markdown table of the metrics within NEAR_EDGE of a band edge. Machines
 * in `frozen` predate the growth programme (their physics must not change). */
export function nearEdgeTable(report: CalibrationReport, frozen: ReadonlySet<string>) {
  const rows = bandMargins(report).filter((m) => m.margin < NEAR_EDGE);
  const lines = [
    `Metrics within ${NEAR_EDGE * 100} % of a band edge at either timestep (from` +
      ' `docs/vehicle-calibration.json`; † predates the catalogue growth and is frozen):',
    '',
    '| Machine | Metric | Edge | Measured | Band edge | Margin |',
    '|---|---|---|---:|---:|---:|',
  ];
  for (const m of rows) {
    const [label, digits, unit] = METRIC[m.metric] ?? [m.metric, 3, ''];
    lines.push(
      `| ${m.name}${frozen.has(m.id) ? ' †' : ''} | ${label} | ${m.edge} | ` +
        `${m.value.toFixed(digits)}${unit} | ${m.bound}${unit} | ${(m.margin * 100).toFixed(2)} % |`,
    );
  }
  return lines.join('\n');
}
/** The document with its generated near-edge block replaced. */
export function withNearEdgeTable(doc: string, table: string) {
  const begin = doc.indexOf(NEAR_EDGE_BEGIN),
    end = doc.indexOf(NEAR_EDGE_END);
  if (begin < 0 || end < begin) throw new Error('near-edge markers missing');
  return `${doc.slice(0, begin + NEAR_EDGE_BEGIN.length)}\n${table}\n${doc.slice(end)}`;
}
/** The generated block as it stands in the document. */
export function nearEdgeBlock(doc: string) {
  const begin = doc.indexOf(NEAR_EDGE_BEGIN),
    end = doc.indexOf(NEAR_EDGE_END);
  if (begin < 0 || end < begin) return null;
  return doc.slice(begin + NEAR_EDGE_BEGIN.length, end).trim();
}
