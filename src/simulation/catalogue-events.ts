const event = (e: EventDefinition): EventDefinition => Object.freeze({ ...e });
/** `count` entrants cycling through `ids` (class leaders first). */
const cycle = (ids: readonly string[], count: number) =>
  Object.freeze(Array.from({ length: count }, (_, i) => ids[i % ids.length]));
/** [id, name, circuit, ruleset, laps, vehicles, seed, weather, opponents?]:
 * a one-machine field names its id and its opponent count; a mixed field
 * names every entrant. */
type GrownEvent = readonly [
  string,
  string,
  EventDefinition['circuit'],
  string,
  number,
  string | readonly string[],
  number,
  EventDefinition['weather'],
  number?,
];
const grown = ([
  id,
  name,
  circuit,
  ruleset,
  laps,
  vehicles,
  seed,
  weather,
  opponents,
]: GrownEvent) =>
  event({
    id,
    version: 1,
    name,
    circuit,
    mode: 'race',
    ruleset,
    laps,
    opponents: typeof vehicles === 'string' ? (opponents ?? 7) : vehicles.length - 1,
    weather,
    vehicles,
    compound: 'medium',
    seed,
  });
